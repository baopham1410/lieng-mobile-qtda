export const dictionaries: Record<AppLocale, Dict> = { vi, lo }

export function translate(
  locale: AppLocale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = dictionaries[locale][key] ?? dictionaries.vi[key] ?? key
  if (!params) return raw
  return Object.entries(params).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    raw,
  )
}

export function categoryLabel(locale: AppLocale, value: string, fallback?: string): string {
  return translate(locale, `cat.${value}`) !== `cat.${value}`
    ? translate(locale, `cat.${value}`)
    : fallback || value
}
